    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
      String nome = jTextFieldNome.getText().trim();
String especie = jComboBoxEspecie.getSelectedItem().toString();
String porte = jComboBoxPorte.getSelectedItem().toString();

if (nome.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Informe o nome do pet!"
    );

    return;
}

if (jComboBoxTutor.getSelectedItem() == null) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Selecione um tutor!"
    );

    return;
}

String tutorSelecionado =
        jComboBoxTutor.getSelectedItem().toString();

int idTutor = Integer.parseInt(
        tutorSelecionado.split(" - ")[0]
);

DTO.PetDTO pet = new DTO.PetDTO();

pet.setTutorId(idTutor);
pet.setNome(nome);
pet.setEspecie(especie);
pet.setPorte(porte);

DAO.PetDAO petDAO = new DAO.PetDAO();

petDAO.cadastrar(pet);

javax.swing.JOptionPane.showMessageDialog(
        this,
        "Pet cadastrado com sucesso!"
);

jTextFieldNome.setText("");
    }//GEN-LAST:event_jButton1ActionPerformed

