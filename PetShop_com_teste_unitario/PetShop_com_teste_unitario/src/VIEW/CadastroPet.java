    public CadastroPet(String origem, int idTutor) {
    initComponents();

    this.origem = origem;
    this.idTutor = idTutor;

    carregarTutores();

    for (int i = 0; i < jComboBoxTutor.getItemCount(); i++) {

        String item = jComboBoxTutor.getItemAt(i);

        int id = Integer.parseInt(
                item.split(" - ")[0]
        );

        if (id == idTutor) {
            jComboBoxTutor.setSelectedIndex(i);
            break;
        }
    }

    jComboBoxTutor.setEnabled(false);
}

    private void carregarTutores() {

    DAO.TutorDAO tutorDAO = new DAO.TutorDAO();

    for (DTO.TutorDTO tutor : tutorDAO.listar()) {

        jComboBoxTutor.addItem(
            tutor.getIdTutor() + " - " + tutor.getNome()
        );
    }
}
    
    
