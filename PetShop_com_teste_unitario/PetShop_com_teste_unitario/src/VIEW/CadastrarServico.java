    private void jButtonCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCadastrarActionPerformed
        String nome = jTextFieldNome.getText().trim();
String precoTexto = jTextFieldPreco.getText().trim();

if (nome.isEmpty() || precoTexto.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Preencha todos os campos!"
    );

    return;
}

double preco;

try {

    preco = Double.parseDouble(
            precoTexto.replace(",", ".")
    );

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Digite um preço válido!"
    );

    return;
}

boolean ativo = jCheckBoxAtivo.isSelected();

DTO.ServicoDTO servico = new DTO.ServicoDTO();

servico.setNome(nome);
servico.setPreco(preco);
servico.setAtivo(ativo);

DAO.ServicoDAO servicoDAO = new DAO.ServicoDAO();

servicoDAO.cadastrar(servico);

javax.swing.JOptionPane.showMessageDialog(
        this,
        "Serviço cadastrado com sucesso!"
);

jTextFieldNome.setText("");
jTextFieldPreco.setText("");
jCheckBoxAtivo.setSelected(true);

carregarServicos();
    }//GEN-LAST:event_jButtonCadastrarActionPerformed

    private void jButtonStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonStatusActionPerformed
       int indice = jListServicos.getSelectedIndex();

if (indice == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Selecione um serviço!"
    );

    return;
}

String selecionado = jListServicos.getSelectedValue();

int idServico = Integer.parseInt(
        selecionado.split(" - ")[0]
);

DAO.ServicoDAO servicoDAO = new DAO.ServicoDAO();

DTO.ServicoDTO servico =
        servicoDAO.buscarPorId(idServico);

if (servico == null) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Serviço não encontrado!"
    );

    return;
}

servico.setAtivo(!servico.isAtivo());

servicoDAO.alterar(servico);

String mensagem = servico.isAtivo()
        ? "Serviço ativado com sucesso!"
        : "Serviço desativado com sucesso!";

javax.swing.JOptionPane.showMessageDialog(
        this,
        mensagem
);

carregarServicos();
    }//GEN-LAST:event_jButtonStatusActionPerformed

