    private void carregarServicos() {

    DAO.ServicoDAO servicoDAO = new DAO.ServicoDAO();

    javax.swing.DefaultListModel<String> modelo =
            new javax.swing.DefaultListModel<>();

    for (DTO.ServicoDTO servico : servicoDAO.listar()) {

        String status = servico.isAtivo()
                ? "ATIVO"
                : "INATIVO";

        modelo.addElement(
                servico.getIdServico()
                + " - "
                + servico.getNome()
                + " - R$ "
                + String.format("%.2f", servico.getPreco())
                + " - "
                + status
        );
    }

    jListServicos.setModel(modelo);
}
    
