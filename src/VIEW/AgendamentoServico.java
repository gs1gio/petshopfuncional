   public AgendamentoServico(String origem, int idTutor) {

    initComponents();

    setDefaultCloseOperation(
            javax.swing.WindowConstants.DISPOSE_ON_CLOSE
    );

    this.origem = origem;
    this.idTutor = idTutor;

    carregarTutores();
    carregarServicos();
    carregarFuncionarios();

    // Seleciona automaticamente o tutor logado
    for (int i = 0; i < jComboBoxTutor.getItemCount(); i++) {

        String item = jComboBoxTutor.getItemAt(i);

        int id = Integer.parseInt(
                item.split(" - ")[0]
        );

        if (id == idTutor) {

            jComboBoxTutor.setSelectedIndex(i);

            break;
        }
    }

    // tutor não pode alterar o próprio tutor
    jComboBoxTutor.setEnabled(false);

    // Carrega os pets desse tutor
    carregarPetsDoTutor();
}
    
    
    private void carregarTutores() {

    DAO.TutorDAO tutorDAO = new DAO.TutorDAO();

    for (DTO.TutorDTO tutor : tutorDAO.listar()) {

        jComboBoxTutor.addItem(
            tutor.getIdTutor() + " - " + tutor.getNome()
        );
    }
}
    
    
   private void carregarPetsDoTutor() {

    jComboBoxPet.removeAllItems();

    if (jComboBoxTutor.getSelectedItem() == null) {
        return;
    }

    String tutorSelecionado =
            jComboBoxTutor.getSelectedItem().toString();

    int idTutor = Integer.parseInt(
            tutorSelecionado.split(" - ")[0]
    );

    DAO.PetDAO petDAO = new DAO.PetDAO();

    for (DTO.PetDTO pet : petDAO.listarPorTutor(idTutor)) {

        jComboBoxPet.addItem(
            pet.getIdPet() + " - " + pet.getNome()
        );
    }
}
    
   private void carregarServicos() {

    jComboBoxServico.removeAllItems();

    DAO.ServicoDAO servicoDAO = new DAO.ServicoDAO();

    for (DTO.ServicoDTO servico : servicoDAO.listar()) {

        if (servico.isAtivo()) {

            jComboBoxServico.addItem(
                servico.getIdServico()
                + " - "
                + servico.getNome()
                + " - R$ "
                + String.format("%.2f", servico.getPreco())
            );
        }
    }
} 
   
   private void carregarFuncionarios() {

    jComboBoxFuncionario.removeAllItems();

    DAO.FuncionarioDAO funcionarioDAO = new DAO.FuncionarioDAO();

    for (DTO.FuncionarioDTO funcionario : funcionarioDAO.listar()) {

        jComboBoxFuncionario.addItem(
            funcionario.getIdFuncionario()
            + " - "
            + funcionario.getNome()
        );
    }
}
   
   
   
