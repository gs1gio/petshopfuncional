    private void jButtonAgendarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAgendarActionPerformed
        
    
  if (jComboBoxTutor.getSelectedItem() == null
        || jComboBoxPet.getSelectedItem() == null
        || jComboBoxServico.getSelectedItem() == null
        || jComboBoxFuncionario.getSelectedItem() == null) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Selecione tutor, pet, serviço e funcionário!"
    );

    return;
}

String data = jTextFieldData.getText().trim();
String hora = jTextFieldHora.getText().trim();

if (data.isEmpty() || hora.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Informe a data e a hora!"
    );

    return;
}


DateTimeFormatter formatoData =
        DateTimeFormatter.ofPattern("dd/MM/yyyy");

LocalDate dataAgendamento;

try {

    dataAgendamento =
            LocalDate.parse(data, formatoData);

} catch (DateTimeParseException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Data inválida! Use o formato DD/MM/AAAA."
    );

    return;
}


DateTimeFormatter formatoHora =
        DateTimeFormatter.ofPattern("HH:mm");

LocalTime horaAgendamento;

try {

    horaAgendamento =
            LocalTime.parse(hora, formatoHora);

} catch (DateTimeParseException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Hora inválida! Use o formato HH:MM."
    );

    return;
}


/* DEFINE O TUTOR DO AGENDAMENTO */

int idTutorAgendamento;

if ("tutor".equals(origem)) {

    // Se for tutor, usa obrigatoriamente
    // o ID do tutor que fez login.
    idTutorAgendamento = this.idTutor;

} else {

    // Se for funcionário, pode escolher qualquer tutor.
    String tutorSelecionado =
            jComboBoxTutor.getSelectedItem().toString();

    idTutorAgendamento = Integer.parseInt(
            tutorSelecionado.split(" - ")[0]
    );
}


String petSelecionado =
        jComboBoxPet.getSelectedItem().toString();

int idPet = Integer.parseInt(
        petSelecionado.split(" - ")[0]
);


String servicoSelecionado =
        jComboBoxServico.getSelectedItem().toString();

int idServico = Integer.parseInt(
        servicoSelecionado.split(" - ")[0]
);


String funcionarioSelecionado =
        jComboBoxFuncionario.getSelectedItem().toString();

int idFuncionario = Integer.parseInt(
        funcionarioSelecionado.split(" - ")[0]
);


DAO.AgendamentoDAO agendamentoDAO =
        new DAO.AgendamentoDAO();

if (agendamentoDAO.horarioOcupado(data, hora)) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Esse horário já está ocupado!"
    );

    return;
}


DTO.AgendamentoDTO agendamento =
        new DTO.AgendamentoDTO();

agendamento.setTutorId(idTutorAgendamento);
agendamento.setPetId(idPet);
agendamento.setServicoId(idServico);
agendamento.setFuncionarioId(idFuncionario);
agendamento.setData(data);
agendamento.setHora(hora);
agendamento.setStatus("CONFIRMADO");


// salvar

agendamentoDAO.cadastrar(agendamento);

javax.swing.JOptionPane.showMessageDialog(
        this,
        "Agendamento realizado com sucesso!"
);


jTextFieldData.setText("");
jTextFieldHora.setText("");
    }//GEN-LAST:event_jButtonAgendarActionPerformed

